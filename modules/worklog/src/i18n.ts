export type WorklogTranslations = (typeof translations)['en']

function getLang(): Lang {
  if (typeof localStorage === 'undefined') return 'it'
  try {
    const stored = localStorage.getItem(STORE_KEY)
    if (stored) {
      const parsed = JSON.parse(stored) as { state?: { language?: string } }
      const lang = parsed.state?.language
      if (lang === 'en' || lang === 'it') return lang
    }
  } catch {
    // ignore
  }
  return 'it'
}

export function useWorklogT(): WorklogTranslations {
  const [lang, setLang] = useState<Lang>(getLang)

  useEffect(() => {
    function onStorage(e: StorageEvent) {
      if (e.key === STORE_KEY) setLang(getLang())
    }
    window.addEventListener('storage', onStorage)
    return () => window.removeEventListener('storage', onStorage)
  }, [])

  return translations[lang]
}
